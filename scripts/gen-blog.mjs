// Bundles every article in src/legacy/content/blog/*.md into one module, so the
// blog works without Vite's import.meta.glob. Runs before `dev` and `build`.
// To publish an article, add a .md file to that folder; this picks it up.
//
// Also emits home-news.generated.js: a tiny module with the three newest
// articles (title/excerpt/date/category/image/slug) plus the article count,
// so the homepage news cards and stats stay in sync with the blog without
// pulling the full article bundle into the homepage.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import YAML from 'yaml'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'src/legacy/content/blog')
const out = path.join(root, 'src/legacy/content/blog-files.generated.js')
const newsOut = path.join(root, 'src/legacy/data/generated/home-news.generated.js')

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort()
const entries = files.map((f) => `  ${JSON.stringify(`../content/blog/${f}`)}: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))},`)
fs.writeFileSync(out, `// Generated by scripts/gen-blog.mjs. Do not edit.\nexport default {\n${entries.join('\n')}\n}\n`)
console.log(`gen-blog: ${files.length} articles`)

// --- homepage news module ------------------------------------------------
const parseFrontmatter = (raw) => {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/)
  return match ? YAML.parse(match[1]) || {} : {}
}

const news = files
  .map((f) => {
    const data = parseFrontmatter(fs.readFileSync(path.join(dir, f), 'utf8'))
    if (!data.slug || !data.title || !data.date) return null
    return {
      title: data.title,
      excerpt: data.excerpt || '',
      date: String(data.date).slice(0, 10),
      category: data.category || 'Foundation',
      image: data.image || '',
      thumb: data.thumb || data.image || '',
      slug: data.slug,
    }
  })
  .filter(Boolean)
  .sort((a, b) => String(b.date).localeCompare(String(a.date)))

const top = news.slice(0, 3).map(({ thumb, image, ...rest }) => ({ ...rest, image: thumb || image }))
const count = news.length

fs.writeFileSync(
  newsOut,
  `// Generated by scripts/gen-blog.mjs. Do not edit.\nexport const articleCount = ${count}\nexport const homeNews = ${JSON.stringify(top, null, 2)}\n`,
)
console.log(`gen-blog: home-news.generated.js (${count} articles, top ${top.length})`)

